#!/bin/bash

# Список всех необходимых пакетов
APPS=(
    # --- Системное и Сборка ---
    "base-devel"            # Инструменты компиляции
    "make"                  # Сборка проектов
    "git"                   # Управление версиями
    "jq"                    # Обработка JSON (нужна для скриптов)
    "libx11"                # Библиотеки X11
    "xorg-xinput"           # Настройка устройств ввода
    "xorg-xsetroot"         # Настройка параметров корневого окна
    "slop"                  # Выбор области экрана (нужен для maim/scrot)

    # --- Интерфейс и Оконный менеджер ---
    "i3-wm"                 # Оконный менеджер
    "polybar"               # Панель управления
    "rofi"                  # Меню запуска и переключатель окон
    "picom"                 # Композитор (прозрачность и тени)
    "dunst"                 # Сервер уведомлений
    "nitrogen"              # Установка обоев
    "lxappearance"          # Настройка GTK-тем
    "ly"                    # Менеджер входа в систему (TUI)
    "alttab"                # Утилита для переключения окон (Alt-Tab)
    "workstyle-git"             # Автоматические иконки рабочих столов i3

    # --- Терминал и Консольные утилиты ---
    "alacritty"             # Основной эмулятор терминала
    "btop"                  # Мониторинг ресурсов
    "joshuto"               # Копия ranger на Rust
    "ueberzugpp"            # Библиотека для отрисовки картинок в терминале
    "pulsemixer"            # Консольный микшер громкости
    "calcurse"              # Календарь и планировщик в терминале
    "gtt-bin"               # Google Translate TUI
    "lazygit"               # Интерфейс для git
    "vim"                   # Текстовый редактор
    "scrot"                 # Скриншоты

    # --- Прикладное ПО (GUI) ---
    "waterfox-bin"          # Браузер
    "visual-studio-code-bin" # Редактор кода
    "neovim"                # TUI редактор кода
    "obsidian"              # Заметки
    "postman-bin"           # Тестирование API
    "gimp"                  # Графический редактор
    "thunar"                # Легкий файловый менеджер (XFCE)
    "dolphin"               # Файловый менеджер (KDE)
    "kate"                  # Текстовый редактор (KDE)
    "gwenview"              # Просмотр изображений (KDE)

    # --- Сеть и Система ---
    "network-manager-applet" # Аплет Wi-Fi в трее
    "networkmanager"        # Сам менеджер сети
    "docker"                # Контейнеризация
    "docker-compose"        # Оркестрация контейнеров
    "clipmenu"              # Менеджер буфера обмена

    # --- Кастомизация ---
    "wallust"               # Генератор палитр из обоев
    
    # --- Программы ---
    "soulseekqt"            # Утилита для скачивания музыки P2P
    "kew-git"               # TUI Музыкальный плеер

    # --- Важные дополнения для корректной работы ---
    "xclip"                 # Работа с буфером обмена в терминале
    "rsync"                 # Для безопасного копирования конфигов
    "ffmpeg"                # Бибилиотека для взаимодействия с видео
    "tg-ws-proxy-bin"       # Прокси сервер для корректной работы Telegram
    "proxychains-ng"        # Утилита для использования прокси с любыми командами в linux
    "ueberzugpp"            # Утилита отрисовки изображений в joshuto
    "gost"                  # Прокси для прокси. Создает прокси на localhost без авторизации (и подключается к авторизируемым прокси)


    # --- Программы, которые использовались ранее. Для отбратной совместимости. ---
    "ranger"                # Консольный файловый менеджер
)


echo "Начинаю проверку доступности пакетов..."
echo "------------------------------------"

MISSING_APPS=()

for app in "${APPS[@]}"; do
    # Проверяем сначала в официальных репозиториях, затем в AUR.
    # Флаг -q (quiet) скрывает лишний вывод, оставляя только системные ошибки.
    if ! yay -Si "$app" >/dev/null 2>&1 && ! yay -Ai "$app" >/dev/null 2>&1; then
        echo "❌ Пакет НЕ НАЙДЕН: $app"
        MISSING_APPS+=("$app")
    else
        echo "✅ Доступен: $app"
    fi
done

echo "------------------------------------"
if [ ${#MISSING_APPS[@]} -eq 0 ]; then
    echo "🎉 Отлично! Все пакеты найдены и готовы к установке."
else
    echo "⚠️  Внимание! Следующие пакеты (${#MISSING_APPS[@]} шт.) не найдены в репозиториях или AUR:"
    for missing in "${MISSING_APPS[@]}"; do
        echo "  - $missing"
    done
    echo "Исправьте имена перед запуском установки."
    exit 1
fi
